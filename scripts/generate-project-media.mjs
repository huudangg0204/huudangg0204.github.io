import { readdir, writeFile } from 'node:fs/promises'
import { join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const projectRoot = fileURLToPath(new URL('..', import.meta.url))
const mediaRoot = join(projectRoot, 'public', 'assets', 'projects')
const outputFile = join(projectRoot, 'src', 'data', 'projectMedia.generated.js')
const imageExtensions = new Set(['.avif', '.gif', '.jpeg', '.jpg', '.png', '.webp'])
const videoExtensions = new Set(['.mp4', '.ogv', '.webm'])

function extensionOf(fileName) {
  return fileName.slice(fileName.lastIndexOf('.')).toLowerCase()
}

function compareMediaFiles(first, second) {
  const firstIsPreview = first.toLowerCase().startsWith('preview.')
  const secondIsPreview = second.toLowerCase().startsWith('preview.')

  if (firstIsPreview !== secondIsPreview) return firstIsPreview ? -1 : 1
  return first.localeCompare(second, undefined, { numeric: true, sensitivity: 'base' })
}

async function generateProjectMedia() {
  let projectDirectories = []

  try {
    projectDirectories = await readdir(mediaRoot, { withFileTypes: true })
  } catch (error) {
    if (error.code !== 'ENOENT') throw error
  }

  const mediaByProject = {}

  for (const directory of projectDirectories.filter((entry) => entry.isDirectory())) {
    const folder = join(mediaRoot, directory.name)
    const files = await readdir(folder, { withFileTypes: true })
    const fileNames = files.filter((entry) => entry.isFile()).map((entry) => entry.name)
    const imageFiles = fileNames.filter((fileName) => imageExtensions.has(extensionOf(fileName))).sort(compareMediaFiles)
    const videoFiles = fileNames.filter((fileName) => videoExtensions.has(extensionOf(fileName))).sort(compareMediaFiles)
    const toPublicPath = (fileName) => relative(join(projectRoot, 'public'), join(folder, fileName)).replaceAll('\\', '/')

    mediaByProject[directory.name] = {
      galleryImages: imageFiles.map(toPublicPath),
      demoVideo: videoFiles[0] ? toPublicPath(videoFiles[0]) : null,
    }
  }

  const output = `// Generated by scripts/generate-project-media.mjs. Do not edit manually.\nexport default ${JSON.stringify(mediaByProject, null, 2)}\n`
  await writeFile(outputFile, output)
}

generateProjectMedia().catch((error) => {
  console.error('Unable to generate project media manifest:', error)
  process.exitCode = 1
})
